READING = """# ParEval reading

Paper: arXiv:2401.12554, read in full.

## Findings
- [V, p.1] "we run with one process per physical core on every node"
"""


def readings_repo(tmp_path, monkeypatch):
    note = tmp_path / "docs/research/2026-10-27-x/notes/pareval.md"
    note.parent.mkdir(parents=True)
    note.write_text(READING)
    pdf = paper(
        "we run with one process per physical core on every node",
        "arXiv:2401.12554",
        "doi:10.1145/3625549.3658689",
        name="2401.12554v3.pdf",
    )
    monkeypatch.setattr(qc, "load_papers", lambda dirs: [pdf])
    return note.relative_to(tmp_path).as_posix()


def readings_main(monkeypatch, *argv):
    monkeypatch.setattr(sys, "argv", ["readings-index.py", *argv])
    ri.main()


def test_a_doi_alias_joins_the_arxiv_papers_row(tmp_path, monkeypatch):
    note = readings_repo(tmp_path, monkeypatch)
    readings_main(monkeypatch, "add", "--repo", str(tmp_path), "--paper", "doi:10.1145/3625549.3658689",
                  "--note", note, "--depth", "skimmed", "--reader", "r1", "--date", "2026-10-28")
    log = tmp_path / "docs/research/readings/log.jsonl"
    assert json.loads(log.read_text())["note"] == note
    readings_main(monkeypatch, "--repo", str(tmp_path))
    index = (tmp_path / "docs/research/readings/INDEX.md").read_text()
    rows = [s for s in index.splitlines() if s.startswith("| arXiv") or s.startswith("| doi")]
    assert len(rows) == 1
    assert rows[0].startswith(f"| arXiv:2401.12554 | papers/2401.12554v3.pdf | `{note}` (r1) | 2026-10-28 | skimmed | 1 | 1/1 |")
    assert "1 readings of 1 papers." in index


def test_one_line_citing_a_paper_by_two_ids_counts_once(tmp_path, monkeypatch):
    note = tmp_path / readings_repo(tmp_path, monkeypatch)
    note.write_text(READING.replace("node\"", 'node" (arXiv:2401.12554, doi:10.1145/3625549.3658689)'))
    rows, _ = ri.from_notes(tmp_path, [], [note])
    assert [(r["paper"], r["lines"], r["quotes"], r["matched"]) for r in rows.values()] == [
        ("arXiv:2401.12554", 1, 1, 1)
    ]


def test_a_note_outside_the_repo_by_a_relative_path_is_indexed(tmp_path, monkeypatch):
    readings_repo(tmp_path / "repo", monkeypatch)
    (tmp_path / "outside").mkdir()
    (tmp_path / "outside/n.md").write_text(READING)
    (tmp_path / "a/b").mkdir(parents=True)
    monkeypatch.chdir(tmp_path / "a/b")  # not the repo, so the path is not from the repo either
    rows, _ = ri.from_notes(tmp_path / "repo", [], [Path("../../outside/n.md")])
    assert [(r["note"], r["depth"]) for r in rows.values()] == [("../../outside/n.md", "full")]


def test_the_index_never_replaces_one_it_did_not_write(tmp_path, monkeypatch):
    readings_repo(tmp_path, monkeypatch)
    curated = tmp_path / "docs/research/INDEX.md"
    curated.write_text("# Research index\n\nCurated by hand.\n")
    with pytest.raises(SystemExit, match="not written by this script"):
        readings_main(monkeypatch, "--repo", str(tmp_path), "--readings", str(tmp_path / "docs/research"))
    assert curated.read_text() == "# Research index\n\nCurated by hand.\n"
    readings_main(monkeypatch, "--repo", str(tmp_path), "--readings", str(tmp_path / "out"))
    readings_main(monkeypatch, "--repo", str(tmp_path), "--readings", str(tmp_path / "out"))  # its own: rewritten
    assert (tmp_path / "out/INDEX.md").read_text().startswith("# Readings")
    old = tmp_path / "old/INDEX.md"  # written by the DistBench prototype: rewritten too
    old.parent.mkdir()
    old.write_text("# Readings\n\nGenerated by `python3 research-tools/bin/readings-index.py`; do not edit by hand.\n")
    readings_main(monkeypatch, "--repo", str(tmp_path), "--readings", str(tmp_path / "old"))
    assert "(research-gap skill)" in old.read_text()


def split_brief(run, brief):
    run.mkdir()
    (run / "brief.md").write_text(brief)
    return subprocess.run(["bash", str(SCRIPTS / "split-brief.sh"), str(run)], capture_output=True, text=True)


def test_split_brief_gives_each_seat_only_its_own_seed(tmp_path):
    r = split_brief(tmp_path / "ok", "# Brief\nshared\n## Seat a\nseed a\n## Seat b\nseed b\n")
    assert r.returncode == 0
    assert sorted(p.name for p in (tmp_path / "ok").iterdir()) == ["brief-a.md", "brief-b.md"]
    assert (tmp_path / "ok/brief-b.md").read_text() == "# Brief\nshared\n## Seat b\nseed b\n"


def test_split_brief_refuses_a_seat_id_used_twice(tmp_path):
    r = split_brief(tmp_path / "dup", "# Brief\n## Seat a\nseed one\n## Seat a\nseed two\n")
    assert r.returncode == 1
    assert "seat id used twice" in r.stderr
    assert [p.name for p in (tmp_path / "dup").iterdir()] == ["brief.md"]
