"""The research-gap skill's scripts (sam-cc-setup plugin).

quotecheck.py's matching rules: what text counts as the same quote, which lines are Verified, which
paper and page a line cites. Most cases are ones a real research note or PDF produced. Then
readings-index.py's rows and output folder, and split-brief.sh's refusals. No test needs poppler:
PDF text is given directly, or `pdf_text` is faked.
"""

