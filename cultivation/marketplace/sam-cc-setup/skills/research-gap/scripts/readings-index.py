#!/usr/bin/env python3
"""Write <readings>/INDEX.md: one row per paper a research note read.

Usage:
  readings-index.py [--repo DIR] [--papers DIR ...] [--readings DIR] [NOTE ...]
  readings-index.py add --paper ID --note PATH --depth DEPTH [--reader NAME] [--date YYYY-MM-DD]
    [--repo DIR] [--readings DIR]

`--repo` defaults to the git top level of the current directory, else the current directory;
`--readings` to `<repo>/docs/research/readings`; NOTE and `--papers` default as in quotecheck.py.
The index is its own file: link it from a hand-curated `docs/research/INDEX.md`; the script
refuses to replace an INDEX.md it did not write.

A reading is one paper in one note. The first form rebuilds the index from two sources:
- every note's Verified lines, found and tied to papers as quotecheck.py does (a note read a paper
  when one of its Verified lines cites it), with the quotes on those lines checked against the PDF;
- <readings>/log.jsonl, one JSON object per line that `add` appends, so a survey run records a
  paper it read, how fully and by whom, even before or without a Verified line for it.
A log entry for the same paper and note replaces the depth, reader and date the notes give; an
entry naming any id of a local PDF (its arXiv id, a DOI on its first page or in its file name, or
its file stem) is that PDF's paper, so a DOI alias of an arXiv paper joins the arXiv row.

ID is `arXiv:<id>` (no version), `doi:<doi>`, or a PDF's file stem. DEPTH is abstract, skimmed,
full, or repo (read from the project's public code only, the paper text not read). For a reading
taken from the notes, the date is the note's study folder date, else (a note outside a dated
folder) the date of a log entry for that note; the depth is
the first of abstract ("abstract level", "abstract only", "(abs)"), full ("read in full", "read
in depth", "all of the paper", "read whole") or skimmed ("skim") that the note says on its Verified
lines for the paper or their headings, then, for a paper with a local PDF, in the note's preamble
(the assigned papers); else "unstated". File is the PDF's path from the repo root, or
`papers/<name>` for one in a `--papers` folder outside the repo.
"""

import argparse
import datetime
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import quotecheck  # noqa: E402

HEADER = "Generated by `readings-index.py` (research-gap skill); do not edit by hand."
DEPTHS = ("abstract", "skimmed", "full", "repo")
DEPTH_WORDS = [  # (depth, pattern), in the order they are tried
    ("abstract", re.compile(r"abstract[- ]level|abstracts? only|\((?:abs|abstracts?)\)", re.I)),
    ("full", re.compile(r"read (?:\w+ )?in (?:full|depth)|all of the paper|read whole", re.I)),
    ("skimmed", re.compile(r"\bskim", re.I)),
]


def depth_in(texts):
    for depth, pattern in DEPTH_WORDS:
        if any(pattern.search(t) for t in texts):
            return depth
    return None


def file_of(paper, repo):
    try:
        return str(paper.path.resolve().relative_to(repo.resolve()))
    except ValueError:
        return f"papers/{paper.path.name}"


def from_notes(repo, paper_dirs, note_paths):
    """{(paper id, note): reading} for every paper a Verified line cites, and the PDFs."""
    papers, cited, checked, _ = quotecheck.run(repo, paper_dirs, note_paths)
    quotes = {}  # id(claim) -> [(quote, result)]
    for c, q, r in checked:
        quotes.setdefault(id(c), []).append((q, r))
    readings, preambles = {}, {}
    paths = {quotecheck.note_name(p, repo): p for p in note_paths}
    for c in cited:
        pdfs = {}  # paper id -> its PDFs, so a line citing one paper by two ids counts once
        for ref in c.refs:
            pdfs.setdefault(ref.papers[0].id if ref.papers else ref.label, set()).update(ref.papers)
        for pid, local in pdfs.items():
            r = readings.setdefault(
                (pid, c.note),
                {
                    "paper": pid,
                    "files": sorted({file_of(p, repo) for p in local}),
                    "note": c.note,
                    "date": (re.search(r"\d{4}-\d{2}-\d{2}", c.note) or [""])[0],
                    "lines": 0,
                    "quotes": 0,
                    "matched": 0,
                    "misses": [],
                    "context": [],
                },
            )
            r["lines"] += 1
            r["context"] += [c.section, c.text]
            names = {p.path.name for p in local}
            for q, res in quotes.get(id(c), []):
                if res.status == "match" and res.paper not in names:
                    continue  # matched in another paper this line cites
                r["quotes"] += 1
                r["matched"] += res.status == "match"
                if res.status != "match":
                    r["misses"].append(c.line)
    for r in readings.values():
        if r["note"] not in preambles:
            body = paths[r["note"]].read_text(encoding="utf-8").splitlines()
            first = next((i for i, s in enumerate(body) if re.match(r"##+\s", s)), len(body))
            preambles[r["note"]] = body[:first]
        depth = depth_in(r.pop("context"))
        if depth is None and r["files"]:
            depth = depth_in(preambles[r["note"]])
        r["depth"] = depth or "unstated"
        r["reader"] = ""
        r["source"] = "notes"
    return readings, papers


def from_log(path):
    if not path.exists():
        return []
    return [json.loads(s) for s in path.read_text(encoding="utf-8").splitlines() if s.strip()]


def canonical(ident, papers):
    """The id of the local PDF that carries `ident` under any of its ids, else `ident`."""
    low = ident.lower()
    for p in papers:
        if ident in p.ids or low in p.ids or ident == p.path.stem:
            return p.id
    return ident


def build(args):
    out = args.readings / "INDEX.md"
    if out.exists() and HEADER not in out.read_text(encoding="utf-8"):
        sys.exit(f"readings-index: {out} was not written by this script; kept it")
    paper_dirs = args.papers or quotecheck.default_papers(args.repo)
    notes = args.notes or quotecheck.notes_in(args.repo)
    readings, papers = from_notes(args.repo, paper_dirs, notes)
    log = from_log(args.readings / "log.jsonl")
    for entry in log:
        pid = canonical(entry["paper"], papers)
        files = sorted(file_of(p, args.repo) for p in papers if p.id == pid)
        r = readings.setdefault(
            (pid, entry["note"]),
            {"paper": pid, "files": files, "note": entry["note"], "lines": 0},
        )
        r.update({f: entry[f] for f in ("depth", "reader", "date") if entry.get(f)}, source="log")
    note_dates = {e["note"]: e["date"] for e in log if e.get("date")}
    for r in readings.values():
        r["date"] = r["date"] or note_dates.get(r["note"], "")
    rows = []
    for r in sorted(readings.values(), key=lambda r: (r["paper"].lower(), r["date"], r["note"])):
        quotes = f"{r.get('matched', 0)}/{r['quotes']}" if r.get("quotes") else "-"
        misses = ", ".join(map(str, sorted(set(r.get("misses", []))))) or "-"
        reader = f" ({r['reader']})" if r.get("reader") else ""
        rows.append(
            f"| {r['paper']} | {', '.join(r['files']) or '-'} | `{r['note']}`{reader} "
            f"| {r['date']} | {r['depth']} | {r['lines']} | {quotes} | {misses} | {r['source']} |"
        )
    papers = len({r["paper"] for r in readings.values()})
    lines = [
        "# Readings",
        "",
        HEADER,
        "One row per paper per note that read it. Lines: the note's Verified lines citing the paper.",
        "Quotes: Verified quotes found in the PDF over those checked (quotecheck.py); misses give the",
        "note's line numbers. Source: `notes` when derived from the notes, `log` when"
        " `log.jsonl` beside this file adds or overrides it.",
        "",
        "| Paper | File | Note (reader) | Date | Depth | Lines | Quotes | Misses | Source |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        *rows,
        "",
        f"{len(rows)} readings of {papers} papers.",
        "",
    ]
    args.readings.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}: {len(rows)} readings of {papers} papers")


def add(args):
    note = args.repo / args.note
    if not note.is_file():
        sys.exit(f"no note at {note}")
    entry = {
        "paper": args.paper,
        "note": quotecheck.note_name(note, args.repo),
        "depth": args.depth,
        "reader": args.reader or "",
        "date": args.date or datetime.date.today().isoformat(),
    }
    args.readings.mkdir(parents=True, exist_ok=True)
    with open(args.readings / "log.jsonl", "a", encoding="utf-8") as f:
        f.write(json.dumps(entry) + "\n")
    print(f"logged {args.paper} in {args.note} ({args.depth})")


def paper_id(s):
    if not re.fullmatch(r"arXiv:\d{4}\.\d{4,5}|doi:10\.\S+|[\w.-]+", s):
        raise argparse.ArgumentTypeError("use arXiv:<id> without version, doi:<doi>, or a stem")
    return s


def main():
    argv = sys.argv[1:]
    cmd = "add" if argv[:1] == ["add"] else "build"
    prog = "readings-index.py" + (" add" if cmd == "add" else "")
    ap = argparse.ArgumentParser(prog=prog, description=__doc__.split("\n", 1)[0])
    ap.add_argument("--repo", type=Path, default=None)
    ap.add_argument("--readings", type=Path, help="default <repo>/docs/research/readings")
    if cmd == "add":  # `add` first, so a note path never reads as the subcommand
        argv = argv[1:]
        ap.add_argument("--paper", required=True, type=paper_id)
        ap.add_argument("--note", required=True, help="note path relative to the repo")
        ap.add_argument("--depth", required=True, choices=DEPTHS)
        ap.add_argument("--reader", help="who read it: an agent, a run or a person")
        ap.add_argument("--date", type=datetime.date.fromisoformat)
    else:
        ap.add_argument("--papers", type=Path, action="append")
        ap.add_argument("notes", type=Path, nargs="*")
    args = ap.parse_args(argv)
    args.repo = args.repo or quotecheck.default_repo()
    args.readings = args.readings or args.repo / "docs/research/readings"
    if cmd == "add":
        args.date = args.date and args.date.isoformat()
        add(args)
    else:
        build(args)


if __name__ == "__main__":
    main()
